#!/usr/bin/env python3
"""The fifth episode's backgrounds, from the DS.

The DS background table (ARM9 0x020a7a80, 16 bytes an entry: data.bin
offset, size, layout bits, English variant) uses the GBA's numbers and the
GBA's layout bits (BG_MODE_* in include/background.h); the fifth episode's
are entries 0x71-0xf0. Each is a 7-entry archive in data.bin: a 256-colour
palette and six LZ chunks of 8x8 tiles. Where the picture has writing, the
English copy is in a second table (0x020a6b68, 8 bytes an entry) at the
index the first table gives.

The DS pictures of the first four episodes are the GBA's with a margin all
round (measured: 256x192 holds 240x160 at x 8, y 16; 512x192 holds 480x160
at x 16, y 16; 256x384 holds 240x320 at x 8, y 32), so the fifth episode's
are cut the same way. A 384x192 picture (the DS's 360 layout, which the GBA
engine never had) is cut to 360x160 and stored as a 480x160 picture, the
right 120 columns repeating its right edge, with the 480 layout bit.

256-colour pictures keep the DS colour indices (32-255, as the GBA's do);
entries 0-31 are the GBA's interface colours. 16-colour pictures keep the
DS's 16 colours.

The luminol's pictures of the stains it finds (luminol.py) are backgrounds
too; those no script shows go in data/rfta/backgrounds_low.s (section
rfta_low, below the 16 MB line).

Writes graphics/en/rfta/bg/bg_XX.png, data/rfta/backgrounds.s (labels
gGfxRftaBgXX, section rfta_data), include/en_rfta_backgrounds.h (their
declarations) and src/data/en_rfta_background.h (the table entries
0x70-0xf0 for gBackgroundTable). usage: backgrounds.py"""
import os, sys, struct
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..'))
from dsdata import data, lz10
import dsbin
ROOT = os.path.join(HERE, '..', '..', '..')
JP_TABLE, EN_TABLE = 0x020a7a80, 0x020a6b68
FIRST, LAST = 0x70, 0xF0
OUT = os.path.join(ROOT, 'graphics', 'en', 'rfta', 'bg')
FLAGS = [(1 << 0, 'BG_MODE_SIZE_480x160'), (1 << 1, 'BG_MODE_SIZE_360x160'), (1 << 2, 'BG_MODE_SIZE_240x320'),
         (1 << 3, 'BG_MODE_SIZE_240x240'), (1 << 4, 'BG_MODE_HSCROLL_RIGHT'), (1 << 5, 'BG_MODE_HSCROLL_LEFT'),
         (1 << 6, 'BG_MODE_VSCROLL_TOP'), (1 << 7, 'BG_MODE_VSCROLL_DOWN'), (1 << 24, 'BG_MODE_SPECIAL_SPEEDLINE'),
         (1 << 25, 'BG_MODE_SCROLL_SPECIAL_SLOW')]

def entry(i):
    d = dsbin.data(); o = JP_TABLE - dsbin.BASE + 16 * i
    return struct.unpack_from('<4I', d, o)

def en_entry(k):
    d = dsbin.data(); o = EN_TABLE - dsbin.BASE + 8 * k
    return struct.unpack_from('<2I', d, o)

def decode(off, ctrl):
    d = data()
    n = struct.unpack_from('<I', d, off)[0]
    ents = [struct.unpack_from('<II', d, off + 4 + 8 * k) for k in range(n)]
    pal = [((c & 31) << 3, ((c >> 5) & 31) << 3, ((c >> 10) & 31) << 3) for c in struct.unpack_from('<256H', d, off + ents[0][0])]
    a = np.frombuffer(b''.join(lz10(d, off + o) for o, s in ents[1:]), np.uint8)
    if ctrl & 0x80000000:
        a = np.stack([a & 15, a >> 4], 1).reshape(-1)
    wt = 64 if ctrl & 1 else 48 if ctrl & 2 else 32
    t = a.reshape(-1, 8, 8); ht = len(t) // wt
    return t[:ht * wt].reshape(ht, wt, 8, 8).transpose(0, 2, 1, 3).reshape(ht * 8, wt * 8), pal

def crop(img, ctrl):
    h, w = img.shape
    gw = {512: 480, 384: 360, 256: 240}[w]
    gh = h - 32 if h == 192 else h - 64
    x0, y0 = (w - gw) // 2, (h - gh) // 2
    out = img[y0:y0 + gh, x0:x0 + gw]
    if gw == 360:
        out = np.concatenate([out, np.repeat(out[:, -1:], 120, 1)], 1)
    return out

def ui_palette():
    p = Image.open(os.path.join(ROOT, 'graphics/striped_images/backgrounds/court/judge_seat.png')).getpalette()
    return [tuple(p[3 * i:3 * i + 3]) for i in range(32)]

def used_ids():
    import inventory
    return sorted(set(v & 0x7FFF for v in inventory.scan(range(17, 36)).bg) - {0xFFF})

def main():
    os.makedirs(OUT, exist_ok=True)
    ui = ui_palette()
    import luminol
    scripts = set(i for i in used_ids() if i >= FIRST)
    pictures = set(p for _, (_, pics) in enumerate(luminol.scenes()[1:]) for p in pics)
    low = pictures - scripts
    wanted = scripts | pictures
    asm = ['@ generated by tools/en/rfta/backgrounds.py: the fifth episode\'s backgrounds', '\t.section rfta_data, "a"']
    asm_low = ['@ generated by tools/en/rfta/backgrounds.py: the luminol\'s pictures (luminol.py)', '\t.section rfta_low, "a"']
    table = ['// generated by tools/en/rfta/backgrounds.py: gBackgroundTable entries 0x70-0xf0',
             '// (Rise from the Ashes; ids the episode does not use point at BG 1)']
    sheet = []
    for i in range(FIRST, LAST + 1):
        off, size, ctrl, en = entry(i)
        if i not in wanted or off == 0:
            table.append('\t{ .bgData = gGfx_BG001_WrightCoOfficeDay, .controlBits = BG_MODE_SIZE_240x160 | BG_MODE_NO_SCROLL | BG_MODE_8BPP }, // 0x%02X unused' % i)
            continue
        src = en_entry(en)[0] if en != 0x8000 else off
        img, pal = decode(src, ctrl)
        img = crop(img, ctrl)
        bpp = 4 if ctrl & 0x80000000 else 8
        if ctrl & 2:
            ctrl = (ctrl & ~2) | 1
        if bpp == 8:
            pal = ui + pal[32:]
        else:
            pal = pal[:16]
        im = Image.fromarray(img.astype(np.uint8), 'P')
        im.putpalette([v for c in pal for v in c] + [0] * (768 - 3 * len(pal)))
        name = 'bg_%02x' % i
        im.save(os.path.join(OUT, name + '.png'))
        label = 'gGfxRftaBg%02X' % i
        lines = ['', '\t.align 2', '\t.global %s' % label, '%s:' % label, '\t.incbin "graphics/en/rfta/bg/%s.%dbpp.striped"' % (name, bpp)]
        if i in low:
            asm_low += lines
        else:
            asm += lines
        bits = [n for b, n in FLAGS if ctrl & b]
        if not any('SIZE' in n for n in bits): bits.insert(0, 'BG_MODE_SIZE_240x160')
        if not any('SCROLL' in n for n in bits): bits.append('BG_MODE_NO_SCROLL')
        bits.append('BG_MODE_4BPP' if bpp == 4 else 'BG_MODE_8BPP')
        table.append('\t{ .bgData = %s, .controlBits = %s }, // 0x%02X%s' % (label, ' | '.join(bits), i, ' (English variant)' if en != 0x8000 else ''))
        sheet.append((i, Image.fromarray(np.array(pal, np.uint8)[img])))
    open(os.path.join(ROOT, 'data', 'rfta', 'backgrounds.s'), 'w').write('\n'.join(asm) + '\n')
    open(os.path.join(ROOT, 'data', 'rfta', 'backgrounds_low.s'), 'w').write('\n'.join(asm_low) + '\n')
    open(os.path.join(ROOT, 'src', 'data', 'en_rfta_background.h'), 'w').write('\n'.join(table) + '\n')
    labels = [l.split()[1] for l in asm + asm_low if l.startswith('\t.global ')]
    hdr = ['// generated by tools/en/rfta/backgrounds.py', '#ifndef GUARD_EN_RFTA_BACKGROUNDS_H', '#define GUARD_EN_RFTA_BACKGROUNDS_H']
    hdr += ['extern u8 %s[];' % l for l in labels] + ['#endif']
    open(os.path.join(ROOT, 'include', 'en_rfta_backgrounds.h'), 'w').write('\n'.join(hdr) + '\n')
    cols = 6; W, H = 240, 160
    s = Image.new('RGB', (cols * W, ((len(sheet) + cols - 1) // cols) * H))
    for k, (i, im) in enumerate(sheet):
        s.paste(im.crop((0, 0, W, H)), ((k % cols) * W, (k // cols) * H))
    s.save(os.path.join(OUT, '..', 'bg_sheet.png'))
    print('%d backgrounds written' % len(sheet))

if __name__ == '__main__':
    main()
