#!/usr/bin/env python3
"""The fifth episode's animations that are not people, from the DS (command
2F): the courtroom's wide shot with the fifth episode's people in it, and
Angel Starr's box lunches.

The DS's table of them (ARM9 0x020a984c, characters.EFFECT_TABLE) is the
GBA's gAnimationData: each names its frames by a number in the people's
table (characters.ANIM_TABLE), with an origin, a palette slot, a sprite count
and a priority; the graphics and frames are the GBA's format. The GBA has
the first four episodes' (the DS's 0x97-0xb0 are its 0x24-0x3d, translate.
gba_anim); the fifth episode adds

  * 0xb1-0xb7, the wide shot's people: Ema Skye beside Phoenix (0xb3) and
    six witnesses on the stand, seen from the gallery. They go on as the
    GBA's 0x3e-0x44, the DS's numbers less 0x73 like the rest of the wide
    shot. Each takes its tiles where the GBA's own wide-shot people do: the
    witnesses (palette 10) ending at OBJ_VRAM1+0x8c0, where the prosecutor
    starts; Ema in Mia's place by Phoenix (OBJ_VRAM1+0x1c20, palette 14).
  * 0x27-0x3b, the box lunches Angel Starr holds out (one each, laid on top
    of her poses 0x1ca/0x1cb): the GBA's 0x45-0x59. They take the end of the
    person's VRAM (OBJ_VRAM0+0x8000 less the largest lunch; characters.py
    gives those two poses a version that leaves it free) and palette 13,
    the speech bubbles' (no bubble comes while a lunch is out), and go with
    her: animation.c moves them with her and ends them when she goes or
    changes pose (as the DS's 0x02022338 does).

The DS positions are about (128, 96) on its 256x192 screen, the GBA's about
(120, 80): the fifth episode's backgrounds are cut from the DS's at x 8,
y 16 (backgrounds.py), so the sprites keep their offsets.

Writes graphics/en/rfta/effects/<DS number>.{pix,seq}, data/rfta/effects.s,
include/en_rfta_effects.h (RFTA_ANIMATION_DATA: the gAnimationData entries)
and tools/en/rfta/effects.json (DS number -> GBA number, for translate.py).
usage: effects.py"""
import os, sys, struct, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..'))
import animfmt
import characters as C
ROOT = os.path.join(HERE, '..', '..', '..')

WIDE = range(0xB1, 0xB8)
WIDE_GBA = 0x3E                      # the GBA's first: 0xb1 - 0x73
WITNESS_END = 0x8C0                  # OBJ_VRAM1: where the GBA's prosecutor (0x2e) starts
DEFENCE_VRAM = 0x1C20                # OBJ_VRAM1: Mia's place by Phoenix (0x25, 0x2f)
LUNCH_GBA = WIDE_GBA + len(WIDE)     # 0x45
LUNCH_PALETTE = 13
LUNCH_PRIORITY = 0x20                # in front of the person (0x21)

def animation(a):
    """(graphics block, frame block with its graphics at offset 0, most sprites, most bytes, table entry)"""
    n, vram, x, y, pal, spr, pri = C.effect_entry(a)
    p, off = C.anim_entry(n)
    gfx = C.entry(2 * p); seq = C.entry(2 * p + 1)
    frames, end = C.parse_anim(seq, off)
    block = bytearray(seq[off:end]); struct.pack_into('<I', block, 4, 0)
    sprites = [animfmt.sprites(bytes(block), f[0]) for f in frames]
    return gfx, bytes(block), max(map(len, sprites)), max(map(C.frame_bytes, sprites)), (vram, x, y, pal, spr, pri)

def main():
    out_dir = os.path.join(ROOT, 'graphics', 'en', 'rfta', 'effects')
    os.makedirs(out_dir, exist_ok=True)
    asm = ['@ The fifth episode\'s wide-shot people and box lunches (tools/en/rfta/effects.py)',
           '\t.section rfta_data, "a"', '']
    hdr = ['// generated by tools/en/rfta/effects.py: the fifth episode\'s animations (command 2F)',
           '#ifndef GUARD_EN_RFTA_EFFECTS_H', '#define GUARD_EN_RFTA_EFFECTS_H', '']
    init = []; mapping = {}
    lunch_vram = C.lunch_vram()
    for a in list(WIDE) + list(C.LUNCHES):
        gfx, seq, most, size, (vram, x, y, pal, spr, pri) = animation(a)
        assert most <= spr, 'animation %x: %d sprites, the DS allows %d' % (a, most, spr)
        assert (x, y) == (128, 96), 'animation %x: origin %d, %d' % (a, x, y)
        name = '%02x' % a
        open(os.path.join(out_dir, name + '.pix'), 'wb').write(gfx)
        open(os.path.join(out_dir, name + '.seq'), 'wb').write(seq)
        asm += ['\t.align 2', '\t.global gRftaEffectPix%s' % name, 'gRftaEffectPix%s:' % name,
                '\t.incbin "graphics/en/rfta/effects/%s.pix"' % name,
                '\t.align 2', '\t.global gRftaEffectSeq%s' % name, 'gRftaEffectSeq%s:' % name,
                '\t.incbin "graphics/en/rfta/effects/%s.seq"' % name, '']
        hdr += ['extern u8 gRftaEffectPix%s[];' % name, 'extern u8 gRftaEffectSeq%s[];' % name]
        if a in WIDE:
            g = WIDE_GBA + a - WIDE[0]
            if pal == 14:            # beside Phoenix
                assert size <= 0x1DA0 - DEFENCE_VRAM
                at = 'OBJ_VRAM1+0x%X' % DEFENCE_VRAM
            else:                    # on the witness stand
                assert pal == 10 and size <= WITNESS_END - 0x140
                at = 'OBJ_VRAM1+0x%X' % (WITNESS_END - size)
            slot, prio = pal, pri
        else:
            g = LUNCH_GBA + a - C.LUNCHES[0]
            at = 'OBJ_VRAM0+0x%X' % (0x8000 - lunch_vram)
            slot, prio = LUNCH_PALETTE, LUNCH_PRIORITY
        mapping['%x' % a] = g
        init.append('    [0x%X] = { .gfxData = gRftaEffectPix%s, .vramPtr = %s, .frameData = gRftaEffectSeq%s, '
                    '.xOrigin = 120, .yOrigin = 80, .paletteSlot = %d, .spriteCount = %d, .priority = %d, .flags = 0 }, \\'
                    % (g, name, at, name, slot, most, prio))
        print('%02x -> GBA %02x: %d sprites, %#x bytes at %s, palette %d' % (a, g, most, size, at, slot))
    hdr += ['',
            '#define RFTA_ANIM_WIDE_FIRST 0x%X' % WIDE_GBA,
            '#define RFTA_ANIM_WIDE_LAST 0x%X' % (WIDE_GBA + len(WIDE) - 1),
            '#define RFTA_ANIM_LUNCH_FIRST 0x%X' % LUNCH_GBA,
            '#define RFTA_ANIM_LUNCH_LAST 0x%X' % (LUNCH_GBA + len(C.LUNCHES) - 1),
            '#define RFTA_LUNCH_PERSON 0x%X' % list(C.LUNCH_POSES)[0],
            '',
            '// gAnimationData entries of the fifth episode\'s animations',
            '#define RFTA_ANIMATION_DATA \\'] + init + ['', '#endif']
    open(os.path.join(ROOT, 'data', 'rfta', 'effects.s'), 'w').write('\n'.join(asm) + '\n')
    open(os.path.join(ROOT, 'include', 'en_rfta_effects.h'), 'w').write('\n'.join(hdr) + '\n')
    json.dump(mapping, open(os.path.join(HERE, 'effects.json'), 'w'), indent=1, sort_keys=True)

if __name__ == '__main__':
    main()
