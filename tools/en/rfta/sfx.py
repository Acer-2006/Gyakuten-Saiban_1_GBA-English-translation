#!/usr/bin/env python3
"""The sound effects Rise from the Ashes added, from the DS's sound archive.

The fifth episode's script plays 25 sounds the first four episodes don't
have: SE073, SE0B6-SE0BE, SE0C2 and SE0D4-SE0E2 (the last are the opening's);
its people's animation frames play six more, SE0C3-SE0C8 (35 frames, 32 of
them Damon Gant's: characters.py).
They are converted the way tools/en/port_sfx.py converts the DS's other sound
effects (the same sequence reading, samples at the pitch the DS plays them,
release rates, squared levels) and become songs 120 and up of the RFTA build,
on the music player the DS plays them on (its PLAYER_AGB_n are the GBA's
players) and with its priority. Several of the opening's are stereo pairs on
the one-track players 2 and 3: those players get two tracks in the RFTA build.

Volumes: tools/en/rfta/sfx_levels.json holds each sound's level in the DS game
and in this build at track volume port_sfx.REF_VOL (made like
tools/en/sfx_levels.json, by sfx_measure.py's method); without it the sounds
play at REF_VOL.

usage: sfx.py DS_sound_data.sdat
writes data/rfta/sfx.s and sound/direct_sound_samples/rfta_sfx/*.bin
       sfx.py --measure DS_DIR GBA_DIR
writes sfx_levels.json from recordings: DS_DIR/d_N.wav (N: the DS sequence),
GBA_DIR/g_N.wav (N: the GBA song, built without sfx_levels.json)"""
import sys, os, json, struct, hashlib
import numpy as np
import ndspy.soundArchive as sa

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..', '..')
sys.path.insert(0, os.path.join(HERE, '..'))
import port_sfx                                   # noqa: E402

# the DS's sequence numbers, in order: GBA songs FIRST_SONG and up
SES = [0x9D] + list(range(0x196, 0x19F)) + [0x1A2] + [0x1B4, 0x1B5, 0x1B6] + list(range(0x1B8, 0x1C3)) + \
      list(range(0x1A3, 0x1A9))         # SE0C3-SE0C8: Gant's (and others') animation frames
FRAME_SE = 0xE0                                   # an animation frame's sound n is SE0nn: the sequence n + 0xE0
FIRST_SONG = 120                                  # after the seven songs (113-119, music.py)
NEW_SES = {d: FIRST_SONG + i for i, d in enumerate(SES)}
PLAYER_TRACKS = {0: 16, 1: 2, 2: 2, 3: 2}         # the RFTA build's players
LEVELS = os.path.join(HERE, 'sfx_levels.json')


class Port(port_sfx.Port):
    def sample(self, w, rate):
        x = port_sfx.wave_pcm(w) if w.waveType != 2 else adpcm(w)
        loop = None
        if w.isLooped:
            loop = w.loopOffset * {0: 4, 1: 2}[w.waveType] if w.waveType != 2 else (w.loopOffset - 1) * 8
        y, l2 = port_sfx.resample_to(x, rate, loop)
        data = np.clip(np.round(y * 128), -128, 127).astype(np.int8).tobytes()
        hdr = struct.pack('<HHIII', 0, 0x4000 if l2 is not None else 0, port_sfx.MIX_RATE * 1024, l2 or 0, len(data))
        blob = hdr + data + (data[l2:l2 + 1] if l2 is not None else b'\0')
        h = hashlib.sha1(blob).hexdigest()[:10]
        self.samples.setdefault(h, ('gRftaSfxSample_%s' % h, blob, 'rfta_sfx/%s.bin' % h))
        return self.samples[h][0]


def adpcm(w):
    from music import adpcm_decode
    return adpcm_decode(bytes(w.data))


def main():
    sdat = sa.SDAT.fromFile(sys.argv[1])
    port_sfx.PLAYER_TRACKS = PLAYER_TRACKS
    levels = json.load(open(LEVELS)) if os.path.exists(LEVELS) else {'songs': {}}
    offset = levels.get('bgm_offset_db', 4.8)
    P = Port(sdat)
    asm = ['@ generated by tools/en/rfta/sfx.py: the sound effects Rise from the Ashes added',
           '\t.include "asm/macros.inc"', '\t.section rfta_data, "a"', '']
    rows = []
    for g, d in sorted((v, k) for k, v in NEW_SES.items()):
        name, seq = sdat.sequences[d]
        player = seq.playerID
        name, tones, tracks = P.song(d, player)
        vol = port_sfx.REF_VOL
        lv = levels['songs'].get(str(g))
        if lv:
            vol = round(port_sfx.REF_VOL * 10 ** (((lv['ds'] - offset) - lv['gba']) / 20))
        if vol > 127:
            print('song %d (%s) wants volume %d: 127' % (g, name, vol))
            vol = 127
        port_sfx.note_peaks(tracks)
        silent = sum(1 for tr in tracks for e in tr if e[2] == 'note' and not e[3]['peak'])
        if silent:                                # (notes at velocity or volume 0: not heard on the DS either)
            tracks = [[e for e in tr if not (e[2] == 'note' and not e[3]['peak'])] for tr in tracks]
            print('song %d (%s): %d silent notes left out' % (g, name, silent))
        peak = max(e[3]['peak'] for tr in tracks for e in tr if e[2] == 'note')
        raw = bytes(seq.eventsData)
        tempo = next((v for t, k, v in port_sfx.sseq_events(raw, port_sfx.sseq_tracks(raw)[0]) if k == 'tempo'), 120)
        sym = 'gRftaSfx%03d' % g
        asm += ['@ song %d: DS %s (sequence 0x%X), player %d, volume %d' % (g, name, d, player, vol),
                '\t.align 2', '%s_voices:' % sym]
        for t in tones:
            if t[0] == 'pcm':
                asm.append('\tvoice_directsound_no_resample 60, 0, %s, 255, 0, 255, %d' % (t[1], t[2]))
            else:
                asm.append('\tvoice_square_2_alt %d, 0, 0, 15, 0' % t[1])
        for k, tr in enumerate(tracks):
            b, loop_at = port_sfx.emit_track(tr, k == 0, tempo, vol, peak)
            asm.append('%s_track%d:' % (sym, k))
            if loop_at is None:
                asm.append('\t.byte ' + ', '.join('0x%02X' % x for x in b))
            else:
                if loop_at:
                    asm.append('\t.byte ' + ', '.join('0x%02X' % x for x in b[:loop_at]))
                asm.append('%s_track%d_loop:' % (sym, k))
                asm.append('\t.byte ' + ', '.join('0x%02X' % x for x in b[loop_at:]) + ', 0xB2')
                asm.append('\t.word %s_track%d_loop' % (sym, k))
        asm += ['\t.align 2', '\t.global %s' % sym, '%s:' % sym,
                '\t.byte %d, 0, %d, 0x80' % (len(tracks), seq.channelPressure), '\t.word %s_voices' % sym]
        asm += ['\t.word %s_track%d' % (sym, k) for k in range(len(tracks))]
        asm.append('')
        rows.append('\tsong %s, %d, %d @ DS %s' % (sym, player, player, name))
    os.makedirs(os.path.join(ROOT, 'sound/direct_sound_samples/rfta_sfx'), exist_ok=True)
    for h, (symb, blob, fn) in sorted(P.samples.items()):
        open(os.path.join(ROOT, 'sound/direct_sound_samples', fn), 'wb').write(blob)
        asm += ['\t.align 2', '%s:' % symb, '\t.incbin "sound/direct_sound_samples/%s"' % fn]
    open(os.path.join(ROOT, 'data/rfta/sfx.s'), 'w').write('\n'.join(asm) + '\n')
    # the song table rows (data/sound_data.s, under .ifdef RFTA)
    sd_path = os.path.join(ROOT, 'data/sound_data.s')
    sd = open(sd_path).read()
    a = sd.index('\t@ RFTA sound effects (tools/en/rfta/sfx.py)\n')
    b = sd.index('\t@ end of the RFTA sound effects\n')
    sd = sd[:a] + '\t@ RFTA sound effects (tools/en/rfta/sfx.py)\n' + '\n'.join(rows) + '\n' + sd[b:]
    open(sd_path, 'w').write(sd)
    print('%d sounds (songs %d-%d), %d samples, %d bytes' % (len(rows), FIRST_SONG, FIRST_SONG + len(rows) - 1,
                                                             len(P.samples), sum(len(v[1]) for v in P.samples.values())))


def measure(ds_dir, gba_dir):
    import sfx_measure
    res = {'bgm_offset_db': sfx_measure.BGM_OFFSET_DB, 'ref_vol': port_sfx.REF_VOL, 'songs': {}}
    for d, g in sorted(NEW_SES.items(), key=lambda kv: kv[1]):
        a, ra = sfx_measure.read(os.path.join(ds_dir, 'd_%d.wav' % d))
        b, rb = sfx_measure.read(os.path.join(gba_dir, 'g_%d.wav' % g))
        wa, wb = sfx_measure.window(a, ra), sfx_measure.window(b, rb)
        if wa is None or wb is None:
            print('song %d: silent (%s %s)' % (g, wa, wb)); continue
        dur = wa[1]
        la, lb = sfx_measure.level(a, ra, wa[0], dur), sfx_measure.level(b, rb, wb[0], dur)
        res['songs'][str(g)] = {'ds': round(la, 2), 'gba': round(lb, 2)}
        print('song %3d (DS 0x%X): DS %6.1f dB  GBA %6.1f dB  -> %+5.1f dB' % (g, d, la, lb, la - sfx_measure.BGM_OFFSET_DB - lb))
    json.dump(res, open(LEVELS, 'w'), indent=1)


if __name__ == '__main__':
    if sys.argv[1] == '--measure':
        measure(sys.argv[2], sys.argv[3])
    else:
        main()
