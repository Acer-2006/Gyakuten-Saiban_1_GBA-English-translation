#!/usr/bin/env python3
"""The fifth episode's "point at it" pictures (script commands 3E / 3F), from the DS.

The DS's table of them (ARM9 0x020aad9c, 0x2c bytes an entry) is the GBA's
gSpotSelectData extended: entries 0-6 are the first four episodes' (the
same sections; the DS's coordinates are the GBA's moved by the margin its
pictures have, 8 across and 16 down), 7-12 the fifth episode's. Their two
areas move back by the same margin. The pointer may go anywhere the
pictures can be pointed at: as far down as the GBA's own entries (row 102,
above the text box) where the areas allow, lower where an area is lower
(the muffler in the crime photo; the text box makes way, en_rfta.c).

Writes src/data/en_rfta_spots.h (entries 7-12 for gSpotSelectData).
usage: spots.py"""
import os, sys, struct
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dsbin
ROOT = os.path.join(HERE, '..', '..', '..')
TABLE, SIZE, FIRST, LAST = 0x020aad9c, 0x2c, 7, 12
DX, DY = 8, 16
GBA_BOTTOM, LOWEST = 102, 144          # the GBA's entries' lowest pointer row; the lowest the pointer can go

def entry(i):
    return struct.unpack_from('<16H4H4B', dsbin.data(), TABLE - dsbin.BASE + SIZE * i)

def main():
    lines = ['// generated by tools/en/rfta/spots.py: gSpotSelectData entries %d-%d' % (FIRST, LAST),
             '// (Rise from the Ashes), from the DS\'s table, moved by the DS pictures\' margin']
    for i in range(FIRST, LAST + 1):
        e = entry(i)
        pts = [(max(0, min(239, e[2 * k] - DX)), max(0, min(159, e[2 * k + 1] - DY))) for k in range(8)]
        first, second = pts[:4], pts[4:]
        # (the second area is mostly the rest of the picture: the near miss)
        bottom = GBA_BOTTOM if min(y for x, y in first) <= GBA_BOTTOM else LOWEST
        quad = lambda q: '{ .points = { %s } }' % ', '.join('{ .x = %d, .y = %d }' % p for p in q)
        lines.append('    { .firstArea = %s, .secondArea = %s, .firstAreaSection = 0x%X, .secondAreaSection = 0x%X, '
                     '.defaultSection = 0x%X, .unk26 = 0, .left = 2, .top = 2, .right = %d, .bottom = %d }, // %d' %
                     (quad(first), quad(second), e[16], e[17], e[18], 240 - 16 - 2, bottom, i))
    open(os.path.join(ROOT, 'src', 'data', 'en_rfta_spots.h'), 'w').write('\n'.join(lines) + '\n')
    print('\n'.join(lines))

if __name__ == '__main__':
    main()
