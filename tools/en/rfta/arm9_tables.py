#!/usr/bin/env python3
"""The fifth episode's per-chapter data, read out of the DS ARM9, where it
sits in the GBA's own formats: the first four episodes' tables there are
byte for byte the GBA's (gCourtPresentData_0_0 at 0x020ac9a4, say), and
the chapter pointer tables run to 35 entries.

  start process      35 bytes at 0x020aaae8   (gCaseStartProcess)
  game-over sections 35 u16   at 0x020aab0c   (gCaseGameoverSections)
  segment setup fns  35 ptrs  at 0x020b421c   (code; rooms.py decompiles them)
  court present      35 ptrs  at 0x020b42a8   (gCourtPresentData)
  initial items      35 ptrs  at 0x020b4334   (gCourtRecordInitialItemLists)
  investigation pres 35 ptrs  at 0x020b43c0   (gInvestigationPresentData)
  room setup fns     35 ptrs  at 0x020b444c   (code)
  room update fns    35 ptrs  at 0x020b44d8   (code)

Writes src/en_rfta_tables.c (the data for chapters 17-34, scenario
indices 17-34 of the GBA) and prints what was read. The DS room numbers
above 0x17 are renumbered (ROOMS) so gMain.roomData keeps its 24 rows and
the save layout stays the base patch's."""
import os, sys, struct
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dsbin
from dsbin import u32, BASE
ROOT = os.path.join(HERE, '..', '..', '..')
START_PROC, GAMEOVER = 0x020aaae8, 0x020aab0c
SEG_SETUP, COURT_PRESENT, INITIAL_ITEMS, INV_PRESENT, ROOM_SETUP, ROOM_UPDATE = \
    0x020b421c, 0x020b42a8, 0x020b4334, 0x020b43c0, 0x020b444c, 0x020b44d8
FIRST, LAST = 17, 34
# DS room number -> GBA room number for the fifth episode (rooms.py uses it too)
ROOMS = {0x16: 0x10, 0x17: 0x11, 0x18: 0x12, 0x19: 0x13, 0x1A: 0x14, 0x1B: 0x15, 0x1C: 0x16, 0x1D: 0x17}
def room(r):
    return ROOMS.get(r, r)

# The DS's "74 A n" questions (whose name is it?) are answered with a
# profile, checked by its own code (0x02087c34) against a table of 12-byte
# records: n, the person, the right answer's section, the wrong answer's. The
# GBA asks them with its 21, the wrong answer being the next section (as the
# DS has them) and the right one an entry of the court present data.
PROMPTS, PROMPT_COUNT = 0x020b1324, 9
# the DS's number for a person -> their profiles in the Court Record (the
# fifth episode's two Emas, two Lanas)
PROMPT_PEOPLE = {0: (0x74, 0xCF), 1: (0x75, 0x76), 2: (0x78,), 6: (0x7B,)}   # Ema, Lana, Jake Marshall, Damon Gant

def prompt_answers(k):
    """court present entries for chapter file k's 74 A questions"""
    import ds_script
    table = {}
    for i in range(PROMPT_COUNT):
        n, person, _, right, wrong = struct.unpack('<BBHII', bytes_at(PROMPTS + 12 * i, 12))
        table[n] = (person, right, wrong)
    out = []
    for si, items in ds_script.sections(k):
        for pos, kind, op, a in items:
            if kind == 'cmd' and op == 0x74 and a[0] == 0xA:
                person, right, wrong = table[a[1]]
                assert wrong == 0x81 + si, (k, si, a)     # (the GBA's 21 takes the next section for a wrong answer)
                for evid in PROMPT_PEOPLE[person]:
                    out.append((0x80 + si, evid, right, 0xFF, 0xFF))
    return out

def bytes_at(addr, n):
    d = dsbin.data(); return d[addr - BASE:addr - BASE + n]

def u16(addr):
    return int.from_bytes(bytes_at(addr, 2), 'little')

def initial_items(addr):
    out = []
    for grp, end in ((0, 0xFE), (1, 0xFF)):
        while True:
            v = bytes_at(addr, 1)[0]; addr += 1; out.append(v)
            if v == end:
                break
    return out

def court_present(addr):
    out = []
    while True:
        a, b, c, d, e = struct.unpack('<HHHBB', bytes_at(addr, 8)); addr += 8
        out.append((a, b, c, d, e))
        if a == 0xFFFF:
            break
    return out

def inv_present(addr):
    out = []
    while True:
        r, ev, pe, end, a, b = struct.unpack('<BBBBHH', bytes_at(addr, 8)); addr += 8
        out.append((room(r), ev, pe, end, a, b))
        if end == 0xFF:
            break
    return out

def main():
    import translate   # (it imports this module)
    procs = bytes_at(START_PROC, 35)
    gameover = [u16(GAMEOVER + 2 * i) for i in range(35)]
    lines = ['// generated by tools/en/rfta/arm9_tables.py from the DS ARM9: the fifth',
             "// episode's chapter data in the GBA's formats (see that file)",
             '#include "global.h"', '#include "main.h"', '#include "case_data.h"', '#include "investigation.h"', '']
    seen = {}
    names = {'court': {}, 'items': {}, 'inv': {}}
    for k in range(FIRST, LAST + 1):
        tag = '5_%02d' % (k - FIRST)
        for kind, table, reader, ctype in (('items', INITIAL_ITEMS, initial_items, 'u8'),
                                           ('court', COURT_PRESENT, court_present, 'struct CourtPresentData'),
                                           ('inv', INV_PRESENT, inv_present, 'struct InvestigationPresentData')):
            addr = u32(table + 4 * k)
            extra = prompt_answers(k) if kind == 'court' else []
            if (kind, addr) in seen and not extra:
                names[kind][k] = seen[(kind, addr)]; continue
            data = reader(addr)
            data = data[:-1] + extra + data[-1:]        # (before the end marker)
            base = {'items': 'gCourtRecordInitialItems_', 'court': 'gCourtPresentData_', 'inv': 'gInvestigationPresentData_'}[kind]
            name = base + tag
            seen[(kind, addr)] = name; names[kind][k] = name
            if kind == 'items':
                lines.append('const u8 %s[%d] = { %s };' % (name, len(data), ', '.join('0x%02x' % v for v in data)))
            elif kind == 'court':
                lines.append('const struct CourtPresentData %s[%d] = {' % (name, len(data)))
                for a, b, c, d, e in data:
                    lines.append('    { .presentingSection = 0x%X, .evidenceId = 0x%X, .presentedSection = 0x%X, .flagId = 0x%X, .action = 0x%X },' % (a, b, c, d, e))
                lines.append('};')
            else:
                lines.append('const struct InvestigationPresentData %s[%d] = {' % (name, len(data)))
                for r, ev, pe, end, a, b in data:
                    lines.append('    { .roomId = 0x%X, .evidenceId = 0x%X, .personId = 0x%X, .end = 0x%X, .interestedSection = 0x%X, .uninterestedSection = 0x%X },' % (r, ev, translate.stand_in(pe), end, a, b))
                lines.append('};')
            lines.append('')
    hdr = ['// generated by tools/en/rfta/arm9_tables.py: the fifth episode\'s entries of the',
           '// chapter tables in case_data.c (chapters 17-34)', '#ifndef GUARD_EN_RFTA_CASE_DATA_H', '#define GUARD_EN_RFTA_CASE_DATA_H', '']
    hdr.append('#define RFTA_CASE_START_PROCESS %s' % ', '.join(str(procs[k]) for k in range(FIRST, LAST + 1)))
    hdr.append('#define RFTA_CASE_GAMEOVER_SECTIONS %s' % ', '.join('0x%X' % gameover[k] for k in range(FIRST, LAST + 1)))
    for kind, macro, ctype in (('items', 'RFTA_COURT_RECORD_INITIAL_ITEMS', 'const u8'),
                               ('court', 'RFTA_COURT_PRESENT_DATA', 'const struct CourtPresentData'),
                               ('inv', 'RFTA_INVESTIGATION_PRESENT_DATA', 'const struct InvestigationPresentData')):
        hdr.append('#define %s %s' % (macro, ', '.join(names[kind][k] for k in range(FIRST, LAST + 1))))
        for n in sorted(set(names[kind].values())):
            hdr.append('extern %s %s[];' % (ctype, n))
    hdr += ['', '#endif']
    open(os.path.join(ROOT, 'include', 'en_rfta_case_data.h'), 'w').write('\n'.join(hdr) + '\n')
    lines.insert(3, '#include "en_rfta.h"')
    lines.insert(4, '#if RFTA')
    lines.append('#endif // RFTA')
    out = os.path.join(ROOT, 'src', 'en_rfta_tables.c')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out)
    print('start processes', [procs[k] for k in range(FIRST, LAST + 1)])
    print('game-over sections', ['%x' % gameover[k] for k in range(FIRST, LAST + 1)])
    for k in range(FIRST, LAST + 1):
        print('chapter %d: setup %08x room setup %08x update %08x' % (k, u32(SEG_SETUP + 4 * k), u32(ROOM_SETUP + 4 * k), u32(ROOM_UPDATE + 4 * k)))

if __name__ == '__main__':
    main()
