#!/usr/bin/env python3
"""The fifth episode's Court Record descriptions, from the DS English data.

The GBA description image (160x64: the name, with the age for people, and
the description below) is drawn as tools/en/make_descriptions.py draws the
first four episodes': the DS English name plate's own pixels, the DS
English description text read exactly out of the DS bitmaps and set again
in the DS dialogue font to the GBA's width.

Where the DS evidence table (tools/en/rfta/evidence.py) keeps them: field 1
is the name plate (EN_NAME), field 3 the info panel (EN_INFO; "Age: 16" for
people) and field 4 the description bitmap (for the first four episodes
fields 3 and 4 are both the entry's own number, which make_descriptions.py
uses). One DS bitmap's text runs past its right edge and wraps round to
the left of the row above (0x9b, "Submitted by Detective Goodman."); it is read
unwrapped.

Writes graphics/en/rfta/descriptions/desc_XX.png, data/rfta/descriptions.s
(gGfxRftaDescriptionXX, section rfta_data) and include/en_rfta_descriptions.h.
Run evidence.py after. usage: descriptions.py [-v]"""
import os, re, sys, json
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, '..'))
import evidence, ds_text, dsfont
import make_descriptions as md
from dsdata import name_plate
ROOT = os.path.join(HERE, '..', '..', '..')
OUT = os.path.join(ROOT, 'graphics', 'en', 'rfta', 'descriptions')
TEMPLATE = os.path.join(ROOT, 'graphics', 'evidence_profile_descriptions', 'evidence', 'air_tube.png.orig')
FIRST = 0x74
TEXT_LEFT = 14                   # the DS description lines start further right than this
# the DS bitmap 0x9b ends "...for deta": the rest of the word went past the
# room the bitmap had even after wrapping round
TRUNCATED = {0x9b: ('for deta', 'for details.')}
# info panel glyphs the first four episodes' ages never used
EXTRA_INFO_GLYPHS = {'3e471ca3866ec09c': '6'}

def description(k):
    """the DS text lines of description bitmap k (as ds_text.description,
    with text that ran past the right edge put back after it)"""
    if ds_text._dl is None:
        ds_text._dl = json.load(open(os.path.join(HERE, '..', 'desc_font_labels.json')))
    a = ds_text.desc_bitmap(k) > 0
    if a[:, :TEXT_LEFT].any():
        # what went past the right edge is at the start of the row above
        wide = np.zeros((a.shape[0], a.shape[1] + TEXT_LEFT), bool)
        wide[:, TEXT_LEFT:a.shape[1]] = a[:, TEXT_LEFT:]
        wide[1:, a.shape[1]:] = a[:-1, :TEXT_LEFT]
        a = wide
    lines = [ds_text.read_line(a[r * 16:(r + 1) * 16], ds_text._dl, 7) for r in range(3)]
    while lines and not lines[-1]:
        lines.pop()
    if k in TRUNCATED and lines[-1].endswith(TRUNCATED[k][0]):
        lines[-1] = lines[-1][:-len(TRUNCATED[k][0])] + TRUNCATED[k][1]
    return lines

def age(k):
    if ds_text._il is None:
        ds_text._il = json.load(open(os.path.join(HERE, '..', 'info_font_labels.json')))
    ds_text._il.update(EXTRA_INFO_GLYPHS)
    try:
        line = ds_text.info_line(k)
    except ValueError:
        return None                  # not a person's panel ("Type: ..." lines use letters not labelled)
    m = re.match(r'Age: ?(.*)$', line)
    return m.group(1) if m and m.group(1) != 'deceased' else None

def build(f):
    base = Image.open(TEMPLATE)
    a = np.array(base).copy()
    a[:, :md.AREA_W] = md.BG
    n = np.array(name_plate(f[1])) == md.DS_NAME_TEXT
    cols = np.where(n.any(0))[0]
    n = n[:, cols[0]:cols[-1] + 1]
    ag = age(f[3]) if f[4] else None   # (no description: a placeholder entry, its panel is Mia's)
    suffix = dsfont.render(' (%s)' % ag) if ag else np.zeros((dsfont.ROWS, 0), np.uint8)
    w = n.shape[1] + suffix.shape[1]
    x0 = (md.AREA_W - w) // 2
    md.put(a, n, x0, md.NAME_SHIFT, md.NAME)
    md.put(a, suffix, x0 + n.shape[1], md.NAME_SHIFT, md.NAME)
    lines = []
    if f[4]:                         # (entries without a description of their own: the name only)
        lines, spacing, (y0, pitch) = md.layout(description(f[4]))
        md.draw_text(a, lines, spacing, y0, pitch)
    im = Image.fromarray(a, 'P'); im.putpalette(base.getpalette())
    return im, ag, lines

def main():
    os.makedirs(OUT, exist_ok=True)
    ents = evidence.entries()
    asm = ['@ generated by tools/en/rfta/descriptions.py: the fifth episode\'s Court Record descriptions',
           '\t.section rfta_data, "a"']
    hdr = ['// generated by tools/en/rfta/descriptions.py', '#ifndef GUARD_EN_RFTA_DESCRIPTIONS_H',
           '#define GUARD_EN_RFTA_DESCRIPTIONS_H']
    report = []
    for i in range(FIRST, len(ents)):
        f = ents[i]
        if not f[1] and not f[4]:
            continue
        im, ag, lines = build(f)
        name = 'desc_%02x' % i
        im.save(os.path.join(OUT, name + '.png'))
        label = 'gGfxRftaDescription%02X' % i
        asm += ['', '\t.align 2', '\t.global %s' % label, '%s:' % label,
                '\t.incbin "graphics/en/rfta/descriptions/%s.4bpp.lz"' % name]
        hdr.append('extern u8 %s[];' % label)
        report.append('%02x %s%s' % (i, '(%s) ' % ag if ag else '', ' | '.join(lines)))
    hdr.append('#endif')
    open(os.path.join(ROOT, 'data', 'rfta', 'descriptions.s'), 'w').write('\n'.join(asm) + '\n')
    open(os.path.join(ROOT, 'include', 'en_rfta_descriptions.h'), 'w').write('\n'.join(hdr) + '\n')
    if '-v' in sys.argv:
        print('\n'.join(report))
    print('%d descriptions' % len(report))

if __name__ == '__main__':
    main()
